CREATE TABLE IF NOT EXISTS agents (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 agentcode VARCHAR(100) NOT NULL, agentToken VARCHAR(255) NOT NULL UNIQUE,
 secretKey VARCHAR(255) NOT NULL UNIQUE, callbackurl VARCHAR(512) NOT NULL,
 saldo DECIMAL(18,4) NOT NULL DEFAULT 100000,
 probganho INT NOT NULL DEFAULT 35, probbonus INT NOT NULL DEFAULT 5,
 probganhortp INT NOT NULL DEFAULT 40, probganhoinfluencer INT NOT NULL DEFAULT 35,
 probbonusinfluencer INT NOT NULL DEFAULT 5, probganhoaposta INT NOT NULL DEFAULT 35,
 probganhosaldo INT NOT NULL DEFAULT 35
);
CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(191) NOT NULL, agentid INT UNSIGNED DEFAULT 1,
 token VARCHAR(255) UNIQUE, atk VARCHAR(255) UNIQUE,
 saldo DECIMAL(18,4) NOT NULL DEFAULT 0, rtp DOUBLE NOT NULL DEFAULT 0,
 valorapostado DECIMAL(18,4) NOT NULL DEFAULT 0,
 valordebitado DECIMAL(18,4) NOT NULL DEFAULT 0,
 valorganho DECIMAL(18,4) NOT NULL DEFAULT 0,
 isinfluencer TINYINT NOT NULL DEFAULT 0, linha_ganho LONGTEXT,
 email VARCHAR(255), password VARCHAR(255), number_phone VARCHAR(40),
 cpf VARCHAR(32), ref_id VARCHAR(100), ip VARCHAR(64),
 data_registro DATETIME DEFAULT CURRENT_TIMESTAMP, indicadode VARCHAR(191),
 UNIQUE KEY user_agent (username, agentid)
);
CREATE TABLE IF NOT EXISTS spins (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL UNIQUE,
 game_code VARCHAR(100) NOT NULL, json LONGTEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS spins_inicial (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, game_code VARCHAR(100) NOT NULL UNIQUE,
 json LONGTEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS calls (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, iduser INT UNSIGNED NOT NULL,
 gamecode VARCHAR(100) NOT NULL, jsonname INT NOT NULL DEFAULT 1,
 bycall VARCHAR(100) NOT NULL DEFAULT 'system', status VARCHAR(32) NOT NULL DEFAULT 'pending',
 steps INT NOT NULL DEFAULT 0, aw DECIMAL(18,4) NOT NULL DEFAULT 0,
 INDEX pending_calls (iduser, status, gamecode)
);
CREATE TABLE IF NOT EXISTS last_spin (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, token VARCHAR(255) NOT NULL,
 gamename VARCHAR(100) NOT NULL, last_spin_result LONGTEXT,
 UNIQUE KEY player_game (token, gamename)
);
